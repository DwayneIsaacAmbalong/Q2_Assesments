secret_number = 17
max_attempts = 5
attempts = 0

while attempts < max_attempts:
    try:
        guess = int(input("Enter your guess: "))
    except ValueError:
        print("Invalid input. Please enter a whole number.")
        continue

    if guess < 0:
        print("Negative numbers are ignored. Try again.")
        continue

    attempts += 1

    if guess == secret_number:
        print("Congratulations! You guessed the secret number!")
        break
    else:
        remaining = max_attempts - attempts
        print(f"Wrong guess. Attempts remaining: {remaining}")
else:
    print("Game Over!")

