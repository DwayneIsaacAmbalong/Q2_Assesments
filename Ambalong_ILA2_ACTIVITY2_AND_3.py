def main():
    print("=== DATA MANAGEMENT PROGRAM ===\n")

    data_array = []
    print("Step 1: Enter 5 numbers to populate the array.")
    for i in range(5):
        while True:
            try:
                val = int(input(f"  Enter value #{i + 1} (Index {i}): "))
                data_array.append(val)
                break
            except ValueError:
                print("  Invalid input. Please enter a whole number.")

    print("\n--- Current Array Elements ---")
    for index in range(len(data_array)):
        print(f"Index [{index}]: {data_array[index]}")

    print("\n--- Indexing & Slicing ---")
    print(f"First element (Index 0): {data_array[0]}")
    print(f"Last element (Index -1): {data_array[-1]}")

    print("\nEnter a slicing range (start and end indices between 0 and 5):")
    start = int(input("  Start index: "))
    end = int(input("  End index: "))

    sub_array = data_array[start:end]
    print(f"Sliced Subarray [{start}:{end}]: {sub_array}")

    print("\n--- Search & Computation ---")
    search_target = int(input("Enter a number to search for in the array: "))

    found_index = -1
    total_sum = 0

    for i in range(len(data_array)):
        total_sum += data_array[i]
        if data_array[i] == search_target and found_index == -1:
            found_index = i

    if found_index != -1:
        print(f"Search Result: Value '{search_target}' found at Index [{found_index}].")
    else:
        print(f"Search Result: Value '{search_target}' was not found in the array.")

    print(f"Computation Result: Sum of all elements = {total_sum}")

    print("\n--- Update Array Value ---")
    while True:
        update_idx = int(input(f"Enter the index to update (0 to {len(data_array) - 1}): "))
        if 0 <= update_idx < len(data_array):
            new_val = int(input(f"Enter the new value for Index [{update_idx}]: "))
            old_val = data_array[update_idx]
            data_array[update_idx] = new_val
            print(f"Success: Updated Index [{update_idx}] from {old_val} to {new_val}.")
            break
        else:
            print("Invalid index. Please choose a number between 0 and 4.")

    print("\n--- Updated Array Elements ---")
    for index, value in enumerate(data_array):
        print(f"Index [{index}]: {value}")
    print("\n=== PROGRAM COMPLETE ===")

if __name__ == "__main__":
    main()

