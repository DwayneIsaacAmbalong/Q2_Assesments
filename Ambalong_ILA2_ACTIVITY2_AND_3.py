def display_scores(scores):
  """Traverses the list and displays elements with their index."""
  print("\n--- Current Quiz Scores ---")
  for index, score in enumerate(scores):
    print(f"Student #{index + 1} (Index {index}): {score}")
  print("---------------------------\n")


def analyze_scores(scores):
  """Performs basic computations (total, average, highest, lowest) on the list."""
  total = sum(scores)
  average = total / len(scores)
  highest = max(scores)
  lowest = min(scores)

  print("--- Score Analysis ---")
  print(f"Total Points:  {total}")
  print(f"Class Average: {average:.2f}")
  print(f"Highest Score: {highest}")
  print(f"Lowest Score:  {lowest}")
  print("----------------------\n")


def search_score(scores, target):
  """Searches for a specific score and reports all matching indices."""
  found_indices = []
  for index, score in enumerate(scores):
    if score == target:
      found_indices.append(index)

  if found_indices:
    print(f"Search Result: Score {target} found at index(es): {found_indices}")
  else:
    print(f"Search Result: Score {target} was not found in the records.")


def update_score(scores, index, new_value):
  """Updates an existing value in the list using its index."""
  if 0 <= index < len(scores):
    old_value = scores[index]
    scores[index] = new_value
    print(
        f"\nUpdate Successful: Index {index} changed from {old_value} to"
        f" {new_value}."
    )
  else:
    print(f"\nError: Index {index} is out of range. No changes made.")


def main():
  # Initial dataset representing student quiz scores
  quiz_scores = [85, 92, 78, 90, 88, 76, 95]

  # 1. Traverse and display initial data
  print("INITIAL DATA:")
  display_scores(quiz_scores)

  # 2. Perform basic computations
  analyze_scores(quiz_scores)

  # 3. Search for specific values
  print("--- Searching Records ---")
  search_score(quiz_scores, 90)
  search_score(quiz_scores, 100)

  # 4. Update a specific value using indexing (e.g., fixing Student #3's score at index 2)
  update_score(quiz_scores, 2, 84)

  # 5. Display the updated list and recalculate stats
  print("\nUPDATED DATA:")
  display_scores(quiz_scores)
  analyze_scores(quiz_scores)


if __name__ == "__main__":
  main()

